from datetime import datetime
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

class GenericEntity(BaseModel):
    """Represents any physical or abstract noun in a project (e.g., Location, Vendor, Person)"""
    entity_id: str = Field(..., description="Unique identifier generated by the engine")
    label: str = Field(..., description="The category type, e.g., 'Location', 'Vendor', 'Person'")
    name: str = Field(..., description="The display name of this entity")
    properties: Dict[str, Any] = Field(default_factory=dict, description="Metadata like costs, contacts, or status flags")

class TimelineEvent(BaseModel):
    """Represents anything that occupies time or has strict execution sequencing"""
    event_id: str = Field(..., description="Unique identifier for the timeline node")
    title: str = Field(..., description="Name of the schedule event, task, or deadline")
    start_time: Optional[datetime] = Field(None, description="Timestamp for when the item begins")
    end_time: Optional[datetime] = Field(None, description="Timestamp for when the item concludes")
    status: str = Field("PENDING", description="Current execution state: PENDING, IN_PROGRESS, COMPLETED")
    associated_entities: List[str] = Field(default_factory=list, description="IDs of GenericEntities linked to this step")
    dependencies: List[str] = Field(default_factory=list, description="IDs of other TimelineEvents that must complete BEFORE this starts")

class SemanticPreference(BaseModel):
    """Represents messy, qualitative human constraints that will live in the Vector DB"""
    preference_id: str = Field(..., description="Unique string tracking the preference card")
    content: str = Field(..., description="The raw user constraint, e.g., 'Must stay within a 15-minute walk of downtown'")
    category: str = Field("general", description="Categorization filter, e.g., 'budget', 'dietary', 'timing'")

class BlueprintWorkspace(BaseModel):
    """The master runtime envelope containing an entire generic tracking roadmap"""
    workspace_id: str = Field(..., description="Unique workspace tenant tracking ID")
    owner_id: str = Field(..., description="The verified user ID who owns this blueprint")
    title: str = Field(..., description="Project workspace name, e.g., 'Summer Trip 2027'")
    entities: List[GenericEntity] = Field(default_factory=list)
    events: List[TimelineEvent] = Field(default_factory=list)
