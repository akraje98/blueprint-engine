from typing import TypedDict, Annotated, List, Dict, Any
from langgraph.graph.message import add_messages

class BlueprintAgentState(TypedDict):
    """
    The central tracking state for the BluePrint LangGraph execution brain.
    Acts as the shared notebook passed between our specialized agent nodes.
    """
    # Automatically appends new conversation messages instead of overwriting them
    messages: Annotated[List[Dict[str, Any]], add_messages]
    
    # Internal routing tracking flags
    current_intent: str
    workspace_id: str
    
    # Structural staging areas for database payloads
    extracted_entities: List[Dict[str, Any]]
    extracted_events: List[Dict[str, Any]]
    extracted_preferences: List[str]
    
    # The evaluation report generated by the Conflict Auditor node
    audit_report: Dict[str, Any]
